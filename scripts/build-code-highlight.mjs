#!/usr/bin/env node
/**
 * Builds the shared Code block highlighter (#1044) from
 * `packages/code-highlight` into the files each renderer ships:
 *
 *  - the Blade renderer's `frontend/code-highlight.{js,css}`, static assets
 *    with no build step of their own;
 *  - `src/support/codeHighlighter.generated.js` in the React and Vue
 *    renderers, which reach npm as source with no runtime dependencies.
 *
 * Output is committed. `--check` fails if it has drifted from the source.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, transformWithEsbuild } from 'vite';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(repoRoot, 'packages', 'code-highlight');
const bladeAssets = 'packages/visual-editor-renderer-blade/resources/assets/frontend';
const generatedModule = 'src/support/codeHighlighter.generated.js';

// Dependency order: each grammar extends the ones above it.
const PRISM_FILES = [
    'components/prism-core',
    'components/prism-markup',
    'components/prism-clike',
    'components/prism-javascript',
    'components/prism-css',
    'components/prism-markup-templating',
    'components/prism-php',
    'components/prism-typescript',
    'components/prism-python',
    'components/prism-ruby',
    'components/prism-go',
    'components/prism-rust',
    'components/prism-json',
    'components/prism-yaml',
    'components/prism-bash',
    'components/prism-sql',
    'components/prism-markdown',
];

/**
 * MIT requires the copyright and permission notice in every copy, and
 * `legalComments: 'none'` drops Prism's own, so the banner carries it and
 * links the full text. The renderers' `NOTICE.md` reproduces it.
 */
const PRISM_VERSION = JSON.parse(
    fs.readFileSync(path.join(repoRoot, 'node_modules', 'prismjs', 'package.json'), 'utf8')
).version;
/**
 * Browsers the generated script supports: Vite 5's former `modules`
 * default. Vite 7 moved its default to "baseline widely available"
 * (Chrome 107, Safari 16), which would quietly drop older browsers from a
 * script that runs on public pages, so the target is pinned here.
 */
const BROWSER_TARGET = ['es2020', 'edge88', 'firefox78', 'chrome87', 'safari14'];

const BANNER =
    `/*! Generated by scripts/build-code-highlight.mjs; do not edit. Includes PrismJS v${PRISM_VERSION}, ` +
    `Copyright (c) 2012 Lea Verou, MIT License, https://github.com/PrismJS/prism/blob/v${PRISM_VERSION}/LICENSE */\n`;

/**
 * Prism's files expect a shared global `Prism`. Concatenated into one
 * function, `var Prism` stands in for it and nothing reaches the real
 * global. The empty `window` keeps Prism from finding a document, so it
 * can't highlight the page by itself or install its worker listener; the
 * empty `module` and `global` stop it exporting itself.
 */
function prismModule() {
    const source = PRISM_FILES.map((file) =>
        fs.readFileSync(path.join(repoRoot, 'node_modules', 'prismjs', `${file}.js`), 'utf8')
    ).join('\n;\n');

    return `export default (function () { var window = {}, module, global;\n${source}\nreturn Prism; })();`;
}

const virtualPrism = {
    name: 'virtual-prism',
    resolveId: (id) => (id === 'virtual:prism' ? '\0virtual:prism' : null),
    load: (id) => (id === '\0virtual:prism' ? prismModule() : null),
};

async function bundle(entry, format) {
    const result = await build({
        configFile: false,
        logLevel: 'error',
        root: sourceDir,
        plugins: [virtualPrism],
        build: {
            write: false,
            minify: false,
            target: BROWSER_TARGET,
            lib: {
                entry: path.join(sourceDir, 'src', entry),
                formats: [format],
                name: 'apCodeHighlight',
                fileName: () => 'bundle.js',
            },
        },
    });
    const { code } = result.output ? result.output[0] : result[0].output[0];
    const minified = await transformWithEsbuild(code, 'bundle.js', { minify: true, legalComments: 'none' });

    return BANNER + minified.code;
}

const moduleBundle = await bundle('module-entry.js', 'es');
const outputs = {
    [`${bladeAssets}/code-highlight.js`]: await bundle('blade-entry.js', 'iife'),
    [`${bladeAssets}/code-highlight.css`]: fs.readFileSync(path.join(sourceDir, 'code-highlight.css'), 'utf8'),
    [`packages/visual-editor-renderer-react/${generatedModule}`]: moduleBundle,
    [`packages/visual-editor-renderer-vue/${generatedModule}`]: moduleBundle,
};

const check = process.argv.includes('--check');
let stale = false;

for (const [relativePath, contents] of Object.entries(outputs)) {
    const target = path.join(repoRoot, relativePath);

    if (!check) {
        fs.writeFileSync(target, contents);
        console.log(`  wrote ${relativePath} (${Buffer.byteLength(contents)} bytes)`);
    } else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== contents) {
        stale = true;
        console.error(`  stale ${relativePath}`);
    }
}

if (stale) {
    console.error('\nCode highlighter output is stale. Run `npm run build:code-highlight`.');
    process.exit(1);
}
